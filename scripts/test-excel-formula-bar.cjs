// TSX_TSCONFIG_PATH=client/tsconfig.app.json node --import tsx scripts/test-excel-formula-bar.cjs
const assert = require('node:assert/strict');
const React = require('../client/node_modules/react');
const { Button, Modal } = require('../client/node_modules/antd');
const Canvas = require('../client/src/components/FieldEditor/MatrixEditor/FreeGridCanvas.tsx').default;
const original = { state: React.useState, ref: React.useRef, effect: React.useEffect, raf: global.requestAnimationFrame };
let slots = [], cursor = 0, patch;
React.useState = initial => { const i = cursor++; if (!(i in slots)) slots[i] = typeof initial === 'function' ? initial() : initial; return [slots[i], next => { slots[i] = typeof next === 'function' ? next(slots[i]) : next; }]; };
React.useRef = initial => React.useState(() => ({ current: initial }))[0];
React.useEffect = () => {};
global.requestAnimationFrame = fn => fn();
const field = { id: 'f', code: 'f', label: 'F', type: 'free_grid', free_table: { rows: [{ id: 'r1' }, { id: 'r2' }, { id: 'total' }], columns: [{ id: 'c', label: '' }], cells: { 'r1::c': '2', 'r2::c': '3' }, input_cells: { 'r1::c': true, 'r2::c': true } } };
const props = { field, template: { groups: [{ id: 'g', fields: [field] }] }, onChange: value => { patch = value; Object.assign(field, value); } };
function nodes(node) { if (Array.isArray(node)) return node.flatMap(nodes); if (!node || typeof node !== 'object' || !node.props) return []; return [node, ...nodes(node.props.children)]; }
function render() { cursor = 0; return Canvas(props); }
const input = tree => nodes(tree).find(n => n.props['aria-label'] === '单元格公式');
const cell = (tree, address) => nodes(tree).find(n => n.props['data-grid-cell'] === address);
const button = (tree, label) => nodes(tree).find(n => n.type === Button && n.props.children === label);
const event = { button: 0, buttons: 1, preventDefault() {}, stopPropagation() {} };
try {
  let tree = render();
  cell(tree, '2-0').props.onMouseDown(event); tree = render();
  const table = nodes(tree).find(n => n.type === 'table');
  table.props.onKeyDown({ ...event, key: '=', target: table, currentTarget: table }); tree = render();
  assert.equal(input(tree).props.value, '=');
  input(tree).props.onChange({ target: { value: '=SUM(A1:A2)' } }); tree = render();
  assert.match(cell(tree, '0-0').props.style.boxShadow, /1677ff/);
  assert.equal(patch, undefined, 'typing does not write data');
  assert.equal(button(tree, '完成').props.disabled, false);
  button(tree, '完成').props.onClick(); tree = render();
  assert.deepEqual(patch.free_table.cell_formulas['total::c'].sources, ['r1::c', 'r2::c']);
  assert.equal(input(tree).props.value, '=SUM(A1,A2)');
  const saved = JSON.stringify(field);
  input(tree).props.onFocus(); tree = render();
  input(tree).props.onChange({ target: { value: '=99' } }); tree = render();
  input(tree).props.onKeyDown({ ...event, key: 'Escape' }); tree = render();
  assert.equal(JSON.stringify(field), saved, 'Esc restores saved formula');
  input(tree).props.onFocus(); tree = render();
  input(tree).props.onChange({ target: { value: '=SU' } }); tree = render();
  assert.ok(nodes(tree).some(n => n.props['aria-label'] === '函数补全'));
  const suggestions = nodes(tree).find(n => n.props['aria-label'] === '函数补全');
  assert.equal(suggestions.props.style.position, 'absolute', 'suggestions overlay the table without adding a toolbar row');
  assert.equal(nodes(suggestions).find(n => n.props.role === 'option').type, 'div', 'suggestions are list rows, not blue buttons');
  input(tree).props.onBlur(); tree = render();
  assert.ok(!nodes(tree).some(n => n.props['aria-label'] === '函数补全'), 'dropdown closes when formula input loses focus');
  input(tree).props.onFocus(); tree = render();
  input(tree).props.onKeyDown({ ...event, key: 'Tab' }); tree = render();
  assert.equal(input(tree).props.value, '=SUM(');
  cell(tree, '0-0').props.onMouseDown(event); tree = render();
  assert.equal(input(tree).props.value, '=SUM(A1');
  assert.match(cell(tree, '0-0').props.style.boxShadow, /1677ff/, 'incomplete formula highlights its reference');
  cell(tree, '1-0').props.onMouseEnter(event); tree = render();
  assert.equal(input(tree).props.value, '=SUM(A1:A2', 'drag replaces the initial reference');
  cell(tree, '0-0').props.onMouseEnter(event); tree = render();
  assert.equal(input(tree).props.value, '=SUM(A1', 'drag can shrink back');
  assert.equal(JSON.stringify(field), saved, 'reference selection keeps saved data unchanged');
  input(tree).props.onChange({ target: { value: '=SUM(A1:A2)' } }); tree = render();
  input(tree).props.onKeyDown({ ...event, key: 'Enter' }); tree = render();
  assert.deepEqual(field.free_table.cell_formulas['total::c'].sources, ['r1::c', 'r2::c'], 'formula target never moves to clicked sources');
  input(tree).props.onFocus(); tree = render();
  input(tree).props.onChange({ target: { value: '=SUM(A1)+10' } }); tree = render();
  input(tree).props.onSelect({ currentTarget: { selectionStart: 5, selectionEnd: 7 } }); tree = render();
  cell(tree, '1-0').props.onMouseDown(event); tree = render();
  assert.equal(input(tree).props.value, '=SUM(A2)+10', 'replace selected source without losing suffix');
  input(tree).props.onKeyDown({ ...event, key: 'Escape' });
  tree = render();
  assert.equal(button(tree, '编辑'), undefined, 'no legacy edit-card entry');
  assert.equal(button(tree, '设置公式'), undefined);
  const beforeZoom = JSON.stringify(field);
  nodes(tree).find(n => n.props['aria-label'] === '缩小表格').props.onClick(); tree = render();
  assert.equal(nodes(tree).find(n => n.type === 'table').props.style.zoom, 0.9);
  assert.ok(parseFloat(cell(tree, '0-0').props.style.border) * 0.9 >= 1, 'gridlines keep at least one screen pixel when zoomed out');
  assert.equal(JSON.stringify(field), beforeZoom, 'view zoom does not modify template/PDF dimensions');
  button(tree, '公式库').props.onClick(); tree = render();
  assert.equal(nodes(tree).find(n => n.type === Modal && n.props.title === '公式库').props.open, true);
  nodes(tree).find(n => n.props['aria-label'] === '搜索公式函数').props.onChange({ target: { value: 'average' } }); tree = render();
  const library = nodes(tree).find(n => n.type === Modal && n.props.title === '公式库');
  assert.ok(JSON.stringify(library.props.children).includes('AVERAGE'));
  library.props.onCancel(); tree = render();
  assert.ok(!nodes(tree).some(n => n.props['aria-label'] === '公式编辑面板'));
  field.free_table.cell_formulas['total::c'] = { type: 'average', sources: ['r1::c', 'r2::c'], sample_scope: 'all' };
  tree = render(); input(tree).props.onFocus(); tree = render();
  assert.match(input(tree).props.value, /^=AVERAGE\(/);
  button(tree, '完成').props.onClick(); tree = render();
  assert.equal(field.free_table.cell_formulas['total::c'].type, 'average', 'opening old formula does not migrate it');
  input(tree).props.onFocus(); tree = render();
  input(tree).props.onChange({ target: { value: '=AVERAGE(A1)' } }); tree = render();
  button(tree, '完成').props.onClick(); tree = render();
  assert.deepEqual(field.free_table.cell_formulas['total::c'].sources, ['r1::c']);
  assert.equal(field.free_table.cell_formulas['total::c'].sample_scope, 'all', 'legacy dynamic scope preserved');
  console.log('Excel formula bar: equals trigger, input, highlights, Enter and Esc passed');
} finally {
  React.useState = original.state; React.useRef = original.ref; React.useEffect = original.effect;
  global.requestAnimationFrame = original.raf;
}
