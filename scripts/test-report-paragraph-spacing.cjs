const assert = require('node:assert/strict');
const { JSDOM } = require('../client/node_modules/jsdom');
const dom = new JSDOM('<div id="editor"></div>', { pretendToBeVisual: true });
for (const key of ['window', 'document', 'navigator', 'HTMLElement', 'Element', 'Node', 'NodeFilter', 'MutationObserver', 'DOMParser', 'getComputedStyle']) Object.defineProperty(global, key, { configurable: true, value: dom.window[key] });
global.requestAnimationFrame = dom.window.requestAnimationFrame.bind(dom.window);
global.cancelAnimationFrame = dom.window.cancelAnimationFrame.bind(dom.window);
const { Editor } = require('../client/node_modules/@tiptap/react');
const { reportParagraphExtensions, selectedReportParagraphs, setReportParagraphSpacing, reportEditorValue, reportEditorTextSelection } = require('../client/src/components/ReportEditor/reportParagraphModel.ts');
const { readReportRichDocument } = require('../shared/report-rich-document.ts');
const editor = new Editor({ element: document.getElementById('editor'), extensions: reportParagraphExtensions(), content: '<p>One</p><p>Two</p><p>Three</p>' });
try {
  const original = reportEditorValue(editor);
  editor.commands.setTextSelection(2);
  assert.equal(selectedReportParagraphs(editor).length, 1);
  assert.equal(setReportParagraphSpacing(editor, { spaceAfter: 12, lineGap: 0.9 }), true);
  assert.equal(editor.getJSON().content[0].attrs.spaceAfter, 12);
  assert.equal(editor.getJSON().content[1].attrs.spaceAfter, null);
  assert.equal(document.querySelector('p').style.marginBottom, '12pt');
  assert.equal(document.querySelector('p').style.lineHeight, '1.9');
  const first = reportEditorValue(editor);
  editor.commands.setTextSelection({ from: 2, to: 8 });
  assert.equal(selectedReportParagraphs(editor).length, 2);
  setReportParagraphSpacing(editor, { spaceBefore: 6 });
  assert.deepEqual(editor.getJSON().content.map(p => p.attrs.spaceBefore), [6, 6, null]);
  editor.commands.undo(); assert.equal(reportEditorValue(editor), first, 'one formatting operation is one undo');
  editor.commands.undo(); assert.equal(reportEditorValue(editor), original);
  editor.commands.redo(); assert.equal(reportEditorValue(editor), first);
  editor.commands.setContent(readReportRichDocument(first));
  editor.commands.setTextSelection(2); editor.commands.splitBlock();
  assert.equal(editor.getJSON().content[1].attrs.spaceAfter, 12, 'Enter inherits paragraph attributes');
  assert.equal(editor.getJSON().content[1].attrs.lineGap, 0.9);
  editor.commands.setContent('<p>One</p><p>Two</p>');
  editor.commands.setTextSelection({ from: 1, to: 6 });
  assert.equal(selectedReportParagraphs(editor).length, 1, 'selection ending at next paragraph boundary excludes it');
  const whole = document.createRange(); whole.selectNode(editor.view.dom);
  window.getSelection().removeAllRanges(); window.getSelection().addRange(whole);
  editor.commands.setTextSelection(reportEditorTextSelection(editor));
  assert.equal(selectedReportParagraphs(editor).length, 2, 'browser selection around the entire editor includes every text paragraph');
  setReportParagraphSpacing(editor, { spaceBefore: 8, spaceAfter: 12, lineGap: 0.8 });
  assert.ok(editor.getJSON().content.every(p => p.attrs.spaceBefore === 8 && p.attrs.spaceAfter === 12 && p.attrs.lineGap === 0.8));
  console.log('Paragraph spacing: cursor, multi-paragraph range, CSS, undo/redo, reopen, Enter inheritance and boundary passed');
} finally { editor.destroy(); dom.window.close(); }
