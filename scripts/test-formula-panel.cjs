// TSX_TSCONFIG_PATH=client/tsconfig.app.json node --import tsx scripts/test-formula-panel.cjs
const assert = require('node:assert/strict');
const React = require('../client/node_modules/react');
const ReactDOM = require('../client/node_modules/react-dom');
const { Button, Select, Modal, Input } = require('../client/node_modules/antd');
const Canvas = require('../client/src/components/FieldEditor/MatrixEditor/FreeGridCanvas.tsx').default;
const FormulaArguments = require('../client/src/components/FieldEditor/MatrixEditor/FormulaArguments.tsx').default;
const original = { state: React.useState, ref: React.useRef, effect: React.useEffect, portal: ReactDOM.createPortal, confirm: Modal.confirm, document: global.document, window: global.window, observer: global.ResizeObserver };
let slots = [], cursor = 0, effects = [], confirmation, patch;
React.useState = initial => { const i = cursor++; if (!(i in slots)) slots[i] = typeof initial === 'function' ? initial() : initial; return [slots[i], next => { slots[i] = typeof next === 'function' ? next(slots[i]) : next; }]; };
React.useRef = initial => React.useState(() => ({ current: initial }))[0];
React.useEffect = effect => { effects.push(effect); };
ReactDOM.createPortal = (children, host) => ({ type: 'portal', props: { children, host } });
Modal.confirm = options => { confirmation = options; };
global.document = { body: {} };
global.window = { innerWidth: 1200, addEventListener() {}, removeEventListener() {} };
global.ResizeObserver = class { observe() {} disconnect() {} };
const host = { clientWidth: 700, getBoundingClientRect: () => ({ left: 0 }), querySelector: () => ({ getBoundingClientRect: () => ({ height: 50 }) }), classList: { add() {}, remove() {} } };
const fakeTable = { closest: () => host, parentElement: { getBoundingClientRect: () => ({ left: 24, width: 650 }) } };
const field = { id: 'f', code: 'f', label: 'F', type: 'free_grid', free_table: { rows: [{ id: 'r1' }, { id: 'r2' }, { id: 'total' }], columns: [{ id: 'c' }], cells: { 'r1::c': '2', 'r2::c': '3' }, input_cells: { 'r1::c': true, 'r2::c': true } } };
const props = { field, template: { groups: [{ id: 'g', fields: [field] }] }, onChange: value => { patch = value; } };
function nodes(node) { if (Array.isArray(node)) return node.flatMap(nodes); if (!node || typeof node !== 'object' || !node.props) return []; return [node, ...nodes(node.props.children)]; }
function render() { cursor = 0; effects = []; return Canvas(props); }
const button = (tree, label) => nodes(tree).find(n => n.type === Button && n.props.children === label);
const cell = (tree, address) => nodes(tree).find(n => n.props['data-grid-cell'] === address);
const event = { button: 0, buttons: 1, preventDefault() {}, stopPropagation() {} };
try {
  let tree = render();
  cell(tree, '2-0').props.onMouseDown(event); tree = render();
  assert.equal(button(tree, '设置公式').props.disabled, false);
  button(tree, '设置公式').props.onClick(); tree = render();
  const table = nodes(tree).find(n => n.type === 'table'); table.props.ref.current = fakeTable;
  const positionEffect = effects.find(effect => effect.toString().includes('setFormulaHost'));
  assert.ok(positionEffect, 'formula docking effect exists'); positionEffect(); tree = render();
  const portal = nodes(tree).find(n => n.type === 'portal' && nodes(n).some(x => x.props['aria-label'] === '公式编辑面板'));
  assert.equal(portal.props.host, host, 'panel is inside the drawer, not behind its body portal');
  const panel = nodes(tree).find(n => n.props['aria-label'] === '公式编辑面板');
  assert.equal(button(tree, '正在选区'), undefined);
  assert.equal(button(tree, '选择来源'), undefined, 'formula mode is always selectable without a toggle');
  assert.ok(!JSON.stringify(panel).includes('计算依赖链'), 'internal dependencies are not exposed in the editor');
  assert.equal(panel.props.style.position, 'absolute'); assert.equal(panel.props.style.bottom, 58);
  assert.equal(nodes(tree).find(n => n.type === Select && n.props['aria-label'] === '公式计算方式').props.value, 'sum');
  assert.equal(button(tree, '应用公式').props.disabled, true);
  const sourceCount = tree => nodes(tree).filter(n => n.type === Button && String(n.props['aria-label'] || '').startsWith('移除来源 ')).length;
  cell(tree, '0-0').props.onMouseDown(event); tree = render();
  cell(tree, '1-0').props.onMouseDown(event); tree = render();
  assert.equal(sourceCount(tree), 2, 'individual clicks add independent sources without a modifier');
  cell(tree, '0-0').props.onMouseDown(event); tree = render();
  assert.equal(sourceCount(tree), 1, 'clicking a selected cell removes only that source');
  cell(tree, '0-0').props.onMouseEnter(event); tree = render();
  assert.equal(sourceCount(tree), 1, 'repeated events over the same cell do not toggle it again');
  cell(tree, '0-0').props.onMouseDown(event); tree = render();
  assert.equal(sourceCount(tree), 2, 'a removed cell can be added back');
  cell(tree, '0-0').props.onMouseDown(event); tree = render();
  cell(tree, '1-0').props.onMouseEnter(event); tree = render();
  assert.equal(sourceCount(tree), 2, 'dragging from a selected cell adds the rectangle rather than toggling each cell');
  cell(tree, '2-0').props.onMouseEnter(event); tree = render();
  assert.equal(sourceCount(tree), 2, 'dragging across the result cell preserves the original sources');
  cell(tree, '1-0').props.onMouseEnter(event); tree = render();
  assert.equal(button(tree, '应用公式').props.disabled, false);
  nodes(tree).find(n => n.type === Select && n.props['aria-label'] === '公式计算方式').props.onChange('custom'); tree = render();
  const insertButtons = nodes(tree).filter(n => n.type === Button && n.props.title === '插入到公式中');
  assert.equal(insertButtons.length, 2, 'one source button per operand, no duplicate insertion row');
  insertButtons[0].props.onClick(); tree = render();
  assert.match(nodes(tree).find(n => n.type === Input.TextArea).props.value, /^A[12]$/, 'the single source row still inserts aliases into custom formulas');
  const beforeLibrary = nodes(tree).find(n => n.type === Input.TextArea).props.value;
  button(tree, 'fx 公式库').props.onClick(); tree = render();
  const sqrtCard = nodes(tree).find(n => n.type === 'div' && n.props.style?.minHeight === 150 && nodes(n).some(child => child.type === 'b' && child.props.children === '平方根'));
  button(sqrtCard, '选择此函数').props.onClick(); tree = render();
  const argumentsCard = nodes(tree).find(n => n.type === FormulaArguments);
  assert.equal(argumentsCard.props.item.name, '平方根');
  assert.equal(nodes(tree).find(n => n.type === Input.TextArea).props.value, beforeLibrary, 'choosing a function does not immediately modify the formula');
  argumentsCard.props.onInsert('SQRT(A1)'); tree = render();
  assert.equal(nodes(tree).find(n => n.type === Input.TextArea).props.value, `(${beforeLibrary}) + (SQRT(A1))`, 'confirmed function preserves the existing expression');
  nodes(tree).find(n => n.type === Select && n.props['aria-label'] === '公式计算方式').props.onChange('sum'); tree = render();
  button(tree, '取消').props.onClick(); assert.ok(confirmation, 'dirty cancel requires confirmation');
  assert.equal(patch, undefined, 'draft and cancel prompt never write formula');
  button(tree, '应用公式').props.onClick();
  assert.deepEqual([...patch.free_table.cell_formulas['total::c'].sources].sort(), ['r1::c', 'r2::c']);
  assert.equal(patch.free_table.cell_formulas['total::c'].type, 'sum');
  assert.ok(!nodes(render()).some(n => n.props['aria-label'] === '公式编辑面板'));
  console.log('Formula panel: drawer docking, common calculation, drag selection, dirty cancel and apply passed');
} finally {
  React.useState = original.state; React.useRef = original.ref; React.useEffect = original.effect; ReactDOM.createPortal = original.portal; Modal.confirm = original.confirm;
  global.document = original.document; global.window = original.window; global.ResizeObserver = original.observer;
}
